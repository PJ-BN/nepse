from collections.abc import AsyncIterator
from dataclasses import dataclass
from datetime import date, datetime
from typing import Protocol

from nepse.domain.market.entities import (
    CorporateActionRecord,
    DailyBar,
    FloorsheetTick,
    IndexBar,
    IndexTick,
    ListedCompany,
    Quote,
)
from nepse.domain.market.session import MarketStatus


@dataclass(frozen=True, slots=True)
class MarketOpen:
    is_open: bool
    as_of: datetime  # last business-day timestamp reported by NEPSE
    market_id: int


class MarketDataSource(Protocol):
    async def market_open(self) -> MarketOpen: ...
    async def live_quotes(self) -> list[Quote]: ...
    async def live_indices(self) -> list[IndexTick]: ...
    async def listed_companies(self) -> list[ListedCompany]: ...
    async def today_prices(self) -> list[DailyBar]: ...
    async def index_bars(self) -> list[IndexBar]: ...
    def floorsheet(self) -> AsyncIterator[list[FloorsheetTick]]: ...
    async def latest_trades(self) -> list[FloorsheetTick]: ...  # newest page of today's floorsheet


class LiveStore(Protocol):
    async def get_status(self) -> MarketStatus | None: ...
    async def get_quotes(self) -> dict[str, Quote]: ...
    async def get_indices(self) -> dict[str, IndexTick]: ...
    async def save(
        self, status: MarketStatus, quotes: dict[str, Quote], indices: dict[str, IndexTick]
    ) -> None: ...
    async def publish(self, topic: str, data: object) -> None: ...
    async def get_last_contract(self) -> int | None: ...
    async def set_last_contract(self, contract_no: int) -> None: ...


class IngestionRepository(Protocol):
    async def upsert_companies(self, companies: list[ListedCompany]) -> int: ...
    async def upsert_daily_bars(self, bars: list[DailyBar]) -> tuple[int, set[str]]: ...
    async def upsert_index_bars(self, bars: list[IndexBar]) -> int: ...
    async def insert_floorsheet(self, ticks: list[FloorsheetTick]) -> tuple[int, set[str]]: ...
    async def upsert_brokers(self, names: dict[int, str]) -> None: ...
    async def refresh_broker_aggregates(self, start: date, end: date) -> None: ...
    async def upsert_corporate_actions(self, actions: list[CorporateActionRecord]) -> tuple[int, set[str]]: ...
    async def earliest_bar_date(self, symbol: str) -> date | None: ...
    async def active_symbols(self) -> list[str]: ...
    async def daily_bars_on(self, day: date) -> list[DailyBar]: ...
    async def floorsheet_days(self, start: date, end: date) -> set[date]: ...  # NPT days that have ticks


class TodayPriceSource(Protocol):
    async def today_prices(self) -> list[DailyBar]: ...


class FloorsheetHistorySource(Protocol):
    def floorsheet_on(self, day: date) -> AsyncIterator[list[FloorsheetTick]]: ...


class HistorySource(Protocol):
    async def history(self, symbol: str, since: date) -> tuple[list[DailyBar], list[CorporateActionRecord]]: ...
